def t_split_throwable(ctx, G):
    fn = ctx.fn(0x0051ED30)  # void SplitThrowableStackBetweenHands(W8Character*, W8EquipSlot)
    for i in range(ctx.n(200)):
        r = ctx.rng('splitthrow', i)
        c = ctx.case('splitthrowablestackbetweenhands.%d' % i, fn, conv='c', ret='v')
        p, s, b, occ = subject_setup(ctx, G, c, r, eq_prob=0.2, bp_prob=0.2)
        q = r.random()
        if q < 0.85:
            slot = r.choice([6, 7])
        else:
            slot = r.choice([0, 3, 8, 9, 11, 12, -1])
        src = {6: 7, 7: 6}.get(slot, 7)
        dst = slot if slot in (6, 7) else 6
        if r.random() < 0.85:
            iid = r.choice(THROWN)
            stack = r.choice([0, 1, 1, 2, 2, 3, 4, 5, 9, 10, 99, 100, r.randint(1, 100), 255])
            put(b, eq_off(src), inst(iid, stack, 0, r.choice([0, 1, 1]), 1, 0, 1, 0, r.randint(0, 1)))
        else:
            iid = hand_item(r)
            stack = 0
            put(b, eq_off(src), rand_inst(r, iid))
        if r.random() < 0.85:
            put(b, eq_off(dst), EMPTY)
        else:
            put(b, eq_off(dst), rand_inst(r, hand_item(r)))
        sanitize(r, b, protect=(eq_off(6), eq_off(7)))
        p.commit(c)
        env(G, c, sel=r.randrange(8))
        row_actions(G, c, r, s)
        set_pool(G, c, gen_pool(r, r.randint(0, 6)))
        c.arg(ctx.char(s)).arg(slot)
        caps_full(ctx, G, c)
        c.note(char=p.names[s], slot=slot, item=iid, stack=stack)


def t_remove_party_item_by_id(ctx, G):
    fn = ctx.fn(0x005215D0)  # bool RemovePartyItemByID(int, bool)
    for i in range(ctx.n(250)):
        r = ctx.rng('removebyid', i)
        c = ctx.case('removepartyitembyid.%d' % i, fn, conv='c', ret='b')
        occ = occupancy(r)
        p = Party(ctx, G, c, r, occupied=occ, quiet=True)
        q = r.random()
        if q < 0.75:
            target = r.choice(SAFE)
        elif q < 0.95:
            target = r.choice(SAFE)   # absent unless planted below
        else:
            target = -1
        plant = q < 0.75
        holders = []
        if plant:
            for s in range(8):
                if r.random() < 0.35:
                    b = p.blob(s)
                    for _ in range(r.choice([1, 1, 2])):
                        off = r.choice([eq_off(r.randrange(12)), bp_off(r.randrange(8))])
                        put(b, off, rand_inst(r, target))
                    holders.append(s)
        p.commit(c)
        pool = gen_pool(r, r.choice([0, 3, r.randint(0, 20)]))
        if plant and r.random() < 0.6:
            for _ in range(r.choice([1, 1, 2, 3])):
                pool.insert(r.randint(0, len(pool)), rand_inst(r, target))
            if r.random() < 0.3 and len(pool) > 1:
                # adjacent duplicates (the compacting pool walk revisits the index)
                j = r.randrange(len(pool))
                pool.insert(j, rand_inst(r, target))
                pool.insert(j, rand_inst(r, target))
        cursor = 1 if r.random() < 0.2 else 0
        hand = rand_inst(r, target if (r.random() < 0.6 and target >= 0) else r.choice(SAFE))
        env(G, c, cursor=cursor, hand=hand, sel=r.randrange(8))
        set_pool(G, c, pool)
        remove_all = r.randint(0, 1)
        c.arg(target).arg(remove_all)
        caps_full(ctx, G, c)
        c.note(item=target, remove_all=remove_all, holders=holders, cursor=cursor, pool=len(pool),
               occ=sorted(occ))


