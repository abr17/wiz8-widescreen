def t_upgrade_class_item(ctx, G):
    fn = ctx.fn(0x005218C0)  # void UpgradeProfessionClassItem(W8Character*)
    for i in range(ctx.n(250)):
        r = ctx.rng('upgradeomni', i)
        c = ctx.case('upgradeprofessionclassitem.%d' % i, fn, conv='c', ret='v')
        p, s, b, occ = subject_setup(ctx, G, c, r, eq_prob=0.1, bp_prob=0.3)
        if r.random() < 0.85:
            level = r.choice(list(range(0, 28)))
        else:
            level = r.choice([30, 40, 50, -1, -100])
        struct.pack_into('<i', b, C_PLEV + 8 * 4, level)
        omni = r.choice(OMNI)
        q = r.random()
        cursor, hand = 0, None
        pool_omni = False
        prot = []
        if q < 0.2:
            where = 'none'
        elif q < 0.4:
            off = r.choice([eq_off(6), eq_off(8)])
            put(b, off, inst(omni, 0, 0, 1, 1, 0, 1, 0, 1))
            prot.append(off)
            where = 'eq'
        elif q < 0.55:
            off = bp_off(r.randrange(8))
            put(b, off, inst(omni, 0, 0, 1, 1, 0, 1, 0, 1))
            prot.append(off)
            where = 'bp'
        elif q < 0.72:
            # found through FindItemByDatabaseKindOnParty (occupied rows only)
            o = (s + r.randint(1, 7)) % 8
            put(p.blob(o), r.choice([eq_off(6), bp_off(r.randrange(8))]), inst(omni, 0, 0, 1, 1, 0, 1, 0, 1))
            where = 'other%d%s' % (o, '' if o in occ else '-unoccupied')
        elif q < 0.92:
            pool_omni = True
            where = 'pool'
        else:
            cursor, hand = 1, inst(omni, 0, 0, 1, 1, 0, 1, 0, 1)
            where = 'hand'
        if r.random() < 0.2:
            for k in range(8):
                if bp_off(k) not in prot:
                    put(b, bp_off(k), rand_inst(r, r.choice(SAFE)))
        sanitize(r, b, protect=prot, extra=ITEMS[599]['weight'])
        p.commit(c)
        env(G, c, cursor=cursor, hand=hand, sel=r.randrange(8))
        row_actions(G, c, r, s)
        n = 500 if r.random() < 0.05 else r.choice([0, 2, r.randint(0, 15)])
        if n == 500:
            make_pool(G, c, r, 500, tail=[inst(omni, 0, 0, 1, 1, 0, 1, 0, 1)] if pool_omni else None)
        else:
            pool = gen_pool(r, n)
            if pool_omni:
                pool.insert(r.randint(0, len(pool)), inst(omni, 0, 0, 1, 1, 0, 1, 0, 1))
            set_pool(G, c, pool)
        c.arg(ctx.char(s))
        caps_full(ctx, G, c)
        c.note(char=p.names[s], level=level, omnigun=omni, where=where, pool=n)


