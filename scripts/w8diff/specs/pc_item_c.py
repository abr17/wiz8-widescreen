def inst(iid, stack=0, uses=0, ident=1, hint=0, u8=0, eff=1, ann=0, bound=0):
    return struct.pack('<iBBBBBBBB', iid, stack & 0xff, uses & 0xff, ident, hint, u8, eff, ann, bound)


EMPTY = inst(-1, ident=0, eff=0)   # what EmptyItemRecord leaves behind


def rand_inst(r, iid, ident=None, bound=None, ann=None):
    if iid == -1:
        return EMPTY
    t = ITEMS[iid]
    stack = uses = 0
    if t['qk'] == 1:
        mx = max(1, t['qmax'])
        stack = r.choice([1, 1, 2, mx, max(1, mx - 1), r.randint(1, mx), r.randint(1, mx)])
    elif t['qk'] in (2, 3, 4):
        uses = r.choice([0, 1, 1, 2, 3, r.randint(0, 9)])
    if ident is None:
        ident = 1 if r.random() < 0.8 else 0
    if bound is None:
        bound = 1 if r.random() < 0.5 else 0
    if ann is None:
        ann = 1 if r.random() < 0.15 else 0
    hint = ident if r.random() < 0.8 else 1 - ident
    return inst(iid, stack, uses, ident, hint, 0, 1, ann, bound)


def eq_off(k):
    return C_EQ + ITEM * k


def bp_off(k):
    return C_BP + ITEM * k


def item_id(blob, off):
    return struct.unpack_from('<i', blob, off)[0]


def put(blob, off, data):
    blob[off:off + len(data)] = data


def hand_item(r):
    p = r.random()
    if p < 0.15:
        return -1
    if p < 0.35:
        return r.choice(WEAP1H)
    if p < 0.45:
        return r.choice(WEAP2H)
    if p < 0.55:
        return r.choice(THROWN)
    if p < 0.68:
        return r.choice(RANGED)
    if p < 0.80:
        return r.choice(AMMO)
    if p < 0.92:
        return r.choice(SHIELD)
    return r.choice(SAFE)


def slot_item(r, k):
    if r.random() < 0.15:
        return -1
    if r.random() < 0.05:
        return r.choice(SAFE)
    if 6 <= k <= 9:
        return hand_item(r)
    return r.choice(_SLOT_ITEMS[k])


def randomize_items(r, blob, eq_prob=0.3, bp_prob=0.3, protect=()):
    for k in range(12):
        if eq_off(k) not in protect and r.random() < eq_prob:
            put(blob, eq_off(k), rand_inst(r, slot_item(r, k)))
    for k in range(8):
        if bp_off(k) not in protect and r.random() < bp_prob:
            put(blob, bp_off(k), rand_inst(r, r.choice(SAFE)) if r.random() < 0.75 else EMPTY)


def carried_weight(blob):
    w = 0
    for off in [eq_off(k) for k in range(12)] + [bp_off(k) for k in range(8)]:
        iid = item_id(blob, off)
        if 0 <= iid < NITEMS:
            stack = blob[off + 4]
            w += ITEMS[iid]['weight'] * (stack if stack > 0 else 1)
    return w


def quiet_items(blob):
    """No plot items on the character, and every backpack item already past its
    one-time reaction: AddItemToCharacter reports backpack[stored index] (even
    for a stack merged into the equipment slot of that index) to
    UpdateFactsAfterAcquiringItem and DeliverExceptionalItemReaction.  Hit
    points at the ceiling: a recomputed lower ceiling then cannot reach zero
    (which would kill the character through SetCharacterCondition)."""
    for off in [eq_off(k) for k in range(12)] + [bp_off(k) for k in range(8)]:
        if item_id(blob, off) in EXCLUDE:
            put(blob, off, EMPTY)
    for k in range(8):
        if item_id(blob, bp_off(k)) != -1:
            blob[bp_off(k) + 9] |= 1
    hpmax = struct.unpack_from('<i', blob, C_HPMAX)[0]
    if hpmax > 0 and struct.unpack_from('<I', blob, C_HP)[0] < hpmax:
        struct.pack_into('<I', blob, C_HP, hpmax)


def sanitize(r, blob, protect=(), extra=0):
    """Hit points at the ceiling; carried weight (plus `extra`) well under a
    conservative carrying capacity (2/3 of (vit + 2*str) * 12, or the stored
    capacity if lower); quiet_items."""
    quiet_items(blob)
    hpmax = struct.unpack_from('<i', blob, C_HPMAX)[0]
    if hpmax > 0 and struct.unpack_from('<I', blob, C_HP)[0] < hpmax:
        struct.pack_into('<I', blob, C_HP, hpmax)
    strength = struct.unpack_from('<I', blob, C_ATTR + 4)[0]
    vit = struct.unpack_from('<I', blob, C_ATTR + 3 * 0x14 + 4)[0]
    cap = (vit + 2 * strength) * 12 * 2 // 3
    stored = struct.unpack_from('<I', blob, C_CAPACITY)[0]
    if 0 < stored < cap:
        cap = stored
    offs = [eq_off(k) for k in range(12)] + [bp_off(k) for k in range(8)]
    while carried_weight(blob) + extra > cap * 0.75:
        cand = [o for o in offs if o not in protect and item_id(blob, o) != -1]
        if not cand:
            # only protected items left: make the character strong instead (and
            # its stored capacity, which RecalculateCarriedWeight compares)
            for a in (0, 3):
                struct.pack_into('<II', blob, C_ATTR + a * 0x14, 125, 125)
            struct.pack_into('<I', blob, C_CAPACITY, 4500)
            break
        put(blob, r.choice(cand), EMPTY)


def emit_diff(c, addr, orig, new, gap=24, limit=12):
    """Write only the changed byte ranges of a structure (after a setb of the
    original), at most `limit` set operations."""
    diffs = [i for i in range(len(new)) if orig[i] != new[i]]
    if not diffs:
        return
    ranges = [[diffs[0], diffs[0] + 1]]
    for i in diffs[1:]:
        if i - ranges[-1][1] <= gap:
            ranges[-1][1] = i + 1
        else:
            ranges.append([i, i + 1])
    while len(ranges) > limit:
        k = min(range(len(ranges) - 1), key=lambda j: ranges[j + 1][0] - ranges[j][1])
        ranges[k:k + 2] = [[ranges[k][0], ranges[k + 1][1]]]
    for a, b in ranges:
        c.set(addr + a, bytes(new[a:b]))


class Party:
    """Eight corpus characters in the party slots (setb) and the XChar
    occupancy flags; members are modified through .blob(s) and committed with
    .commit(c)."""

    def __init__(self, ctx, G, c, r, occupied=None, slots=range(8), quiet=False):
        self.ctx, self.G, self.slots, self.quiet = ctx, G, list(slots), quiet
        got = ctx.set_party(c, r, slots=self.slots)
        self.orig = {s: bytes(b) for s, b, _ in got}
        self.blobs = {s: b for s, b, _ in got}
        self.names = {s: n for s, _, n in got}
        if occupied is not None:
            for s in range(8):
                c.set(G['xchar'] + s * ROW, bytes([1 if s in occupied else 0]))

    def blob(self, s):
        return self.blobs[s]

    def commit(self, c):
        for s in self.slots:
            if self.quiet:
                quiet_items(self.blobs[s])
            emit_diff(c, self.ctx.char(s), self.orig[s], self.blobs[s])


def occupancy(r, must=()):
    if r.random() < 0.8:
        return set(range(8))
    occ = {s for s in range(8) if r.random() < 0.7}
    occ.update(must)
    return occ


def env(G, c, screen=SCREEN_NEUTRAL, combat=0, itemsel=0, npcdlg=0, camp=0, lock=0, trap=0,
        started=1, sel=0, cursor=0, hand=None, pmove=0):
    c.set(G['screen'], struct.pack('<i', screen))
    c.set(G['xs'] + XS_COMBAT, bytes([combat, 0, itemsel, npcdlg, 0, 0, 0, camp, lock, trap]))
    c.set(G['xs'] + XS_PMOVE, bytes([pmove]))
    c.set(G['xs'] + XS_CURSOR, struct.pack('<i', -1))
    c.set(G['gs'] + GS_STARTED, bytes([started]))
    c.set(G['gs'] + GS_SEL, struct.pack('<i', sel))
    c.set(G['gs'] + GS_CURSOR, bytes([cursor]) + (hand if hand is not None else EMPTY))
    c.set(G['gs'] + GS_LOGFACTS, b'\0')
    # the party-wide modifier block the derived-stat rebuild folds in (party spell
    # effects can expire at different frames in the two processes): none
    c.fill(G['gs'] + GS_PARTY_MODS, MODS_SIZE, 0)


def gen_pool(r, n, ids=None):
    return [rand_inst(r, r.choice(ids or SAFE)) for _ in range(n)]


def set_pool(G, c, entries, full=False):
    if full:
        # 500 entries of item 0 (fill), the given entries over the front
        c.fill(G['gs'] + GS_POOL, 500 * ITEM, 0)
        if entries:
            c.set(G['gs'] + GS_POOL, b''.join(entries))
        c.set(G['gs'] + GS_COUNT, struct.pack('<I', 500))
        return
    if entries:
        c.set(G['gs'] + GS_POOL, b''.join(entries))
    c.set(G['gs'] + GS_COUNT, struct.pack('<I', len(entries)))


def pool_size(r, big=0.08):
    p = r.random()
    if p < big / 2:
        return 499
    if p < big:
        return 500
    return r.choice([0, 1, 2, 3, r.randint(0, 12), r.randint(0, 40)])


def make_pool(G, c, r, n, ids=None, tail=None):
    """n entries (499/500: filled with item 0, `tail` entries written at the
    end); returns the list of entries written at the front."""
    if n >= 499:
        c.fill(G['gs'] + GS_POOL, 500 * ITEM, 0)
        front = gen_pool(r, r.randint(0, 6), ids)
        if front:
            c.set(G['gs'] + GS_POOL, b''.join(front))
        if tail:
            c.set(G['gs'] + GS_POOL + (n - len(tail)) * ITEM, b''.join(tail))
        c.set(G['gs'] + GS_COUNT, struct.pack('<I', n))
        return front
    entries = gen_pool(r, n, ids)
    set_pool(G, c, entries)
    return entries


def row_actions(G, c, r, s):
    action = r.choice([-1, 0, 0, 1, 4, 7, 8])
